import { describe, expect, test } from 'bun:test';
import { classify, isWhitespaceOnly } from '../src/review/classify.ts';
import { buildTree, segments, sortFiles, weight } from '../src/review/model.ts';
import { findSameEdits, normaliseLine } from '../src/review/sameEdit.ts';
import type { DiffLine, FileDiff, FileSummary } from '../src/shared/types.ts';

const summary = (path: string, overrides: Partial<FileSummary> = {}): FileSummary => ({
  path,
  status: 'modified',
  additions: 1,
  deletions: 1,
  viewed: false,
  ...overrides,
});
const diffLines = (spec: string): DiffLine[] =>
  spec.split('\n').map(row => ({
    kind: row[0] === '+' ? 'addition' : row[0] === '-' ? 'deletion' : row[0] === '@' ? 'hunk' : 'context',
    text: row.slice(1),
  }));
const fileDiff = (path: string, spec: string, overrides: Partial<FileDiff> = {}): FileDiff => ({
  path,
  lines: diffLines(spec),
  complete: true,
  source: 'entries',
  ...overrides,
});

describe('classify', () => {
  const cases: [FileSummary, FileDiff | undefined, string][] = [
    [summary('src/x.ts', { status: 'renamed', additions: 0, deletions: 0 }), undefined, 'renamed'],
    [summary('src/x.ts', { status: 'renamed', additions: 2, deletions: 1 }), undefined, 'review'],
    [summary('src/x.ts', { status: 'deleted' }), undefined, 'deleted'],
    [summary('bun.lock'), undefined, 'lockfile'],
    [summary('app/package.json'), undefined, 'review'],
    [summary('app/Podfile.lock'), undefined, 'lockfile'],
    [summary('gen/api.ts', { isGenerated: true }), undefined, 'generated'],
    [summary('gen/api.ts'), fileDiff('gen/api.ts', ' // @generated by openapi\n+x'), 'review'], // header only counts on early lines with numbers
    [summary('vendor/lib.js', { isVendored: true }), undefined, 'generated'],
    [summary('src/__snapshots__/a.test.tsx.snap'), undefined, 'snapshot'],
    [summary('src/locales/en.json'), undefined, 'translations'],
    [summary('src/locales/format.ts'), undefined, 'review'],
    [summary('src/util.ts'), fileDiff('src/util.ts', '-  return  a;\n+    return a;  '), 'whitespace'],
    [summary('src/a.css'), fileDiff('src/a.css', '-.a .b {}\n+.a.b {}'), 'review'],
    [summary('src/a.ts'), fileDiff('src/a.ts', '-const n = "My App";\n+const n = "MyApp";'), 'review'],
    [summary('src/a.ts'), fileDiff('src/a.ts', '-a();\n-b();\n+b();\n+a();'), 'review'],
    [summary('src/util.py'), fileDiff('src/util.py', '-  return a\n+    return a'), 'review'],
    [summary('Makefile'), fileDiff('Makefile', '-\tx\n+  x'), 'review'],
    [summary('src/util.ts'), fileDiff('src/util.ts', '-  return  a;\n+  return b;'), 'review'],
    [summary('src/util.ts'), fileDiff('src/util.ts', '-a\n+a', { complete: false }), 'review'],
  ];
  test.each(cases)('%p → %p', (file, diff, want) => expect(classify(file, diff).id).toBe(want as never));
  test('generated header near top of file', () => {
    const diff: FileDiff = {
      path: 'g.ts',
      complete: true,
      source: 'raw',
      lines: [
        { kind: 'hunk', text: '@@' },
        { kind: 'context', text: '// Code generated by protoc. DO NOT EDIT.', oldNumber: 1, newNumber: 1 },
        { kind: 'addition', text: 'x', newNumber: 2 },
      ],
    };
    expect(classify(summary('g.ts'), diff)).toMatchObject({ id: 'generated' });
  });
  test('switched-off buckets fall back to review', () =>
    expect(classify(summary('bun.lock'), undefined, { lockfile: false }).id).toBe('review'));
  test('blank-line-only change is whitespace', () => expect(isWhitespaceOnly(fileDiff('x', '+\n+   \n a'))).toBe(true));
  test('no changes is not whitespace-only', () => expect(isWhitespaceOnly(fileDiff('x', ' a'))).toBe(false));
});

describe('segments (context folding never drops changed lines)', () => {
  const lines = diffLines('@@ -1 +1 @@\n a\n b\n c\n d\n e\n f\n+X\n g\n h\n i\n j\n k\n l\n m\n-Y\n n');
  const folded = segments(lines);
  test('all add/del lines are present', () => {
    const shown = folded.flatMap(segment => ('line' in segment ? [segment.line.text] : []));
    expect(shown).toContain('X');
    expect(shown).toContain('Y');
  });
  test('folds long context, keeps 2 lines around changes', () => {
    expect(folded.filter(segment => 'fold' in segment)).toEqual([{ fold: [1, 5] }, { fold: [10, 13] }]);
    const texts = folded.map(segment =>
      'line' in segment ? segment.line.text : 'fold' in segment ? `…${segment.fold[1] - segment.fold[0]}` : 'gap',
    );
    expect(texts).toEqual(['…4', 'e', 'f', 'X', 'g', 'h', '…3', 'l', 'm', 'Y', 'n']);
  });
  test('second hunk becomes a gap', () => {
    expect(
      segments(diffLines('@@ a\n+x\n@@ b\n+y')).map(segment =>
        'gap' in segment ? 'gap' : 'line' in segment ? segment.line.text : 'fold',
      ),
    ).toEqual(['x', 'gap', 'y']);
  });
  test('short context is not folded', () =>
    expect(segments(diffLines('+a\n b\n c\n d\n e\n f\n+g')).some(segment => 'fold' in segment)).toBe(false));
});

describe('tree / order / weight', () => {
  const tree = buildTree(['README.md', 'apps/mobile/src/a.ts', 'apps/mobile/src/b/c.ts', 'apps/web/x.ts']);
  test('compresses single-child chains, counts files recursively', () => {
    expect(tree.files).toHaveLength(4);
    const apps = tree.children[0]!;
    expect(apps.name).toBe('apps');
    expect(apps.children.map(child => child.name)).toEqual(['mobile/src', 'web']);
    expect(apps.children[0]!.files).toEqual(['apps/mobile/src/a.ts', 'apps/mobile/src/b/c.ts']);
  });
  test('sort puts root files first and groups directories', () => {
    expect(
      sortFiles([{ path: 'b/x' }, { path: 'z.md' }, { path: 'a/y' }, { path: 'a/b' }]).map(file => file.path),
    ).toEqual(['z.md', 'a/b', 'a/y', 'b/x']);
  });
  test('weight is at least 1', () => expect(weight(summary('x', { additions: 0, deletions: 0 }))).toBe(1));
});

describe('same edit', () => {
  const importEdit = (names: string, upPath: string) =>
    `-import { ${names} } from '${upPath}theme';\n+import { ${names} } from '@acme/design-tokens';`;
  const diffs = new Map<string, FileDiff>([
    ['a.tsx', fileDiff('a.tsx', ` x\n${importEdit('colors', '../../')}\n y`)],
    ['b.tsx', fileDiff('b.tsx', importEdit('colors, spacing', '../'))],
    ['c.tsx', fileDiff('c.tsx', importEdit('radii', '../../../'))],
    ['d.tsx', fileDiff('d.tsx', `${importEdit('colors', '../')}\n+trackEvent('x');`)],
    ['e.tsx', fileDiff('e.tsx', '+unrelated')],
  ]);
  const result = findSameEdits(['a.tsx', 'b.tsx', 'c.tsx', 'd.tsx', 'e.tsx'], diffs);
  test('groups identical normalised edits', () => {
    expect(result.groups).toHaveLength(1);
    expect(result.groups[0]!.paths).toEqual(['a.tsx', 'b.tsx', 'c.tsx']);
  });
  test('a file with the edit plus more is tagged, not grouped', () => {
    expect(result.groupByPath.has('d.tsx')).toBe(false);
    expect(result.partialMatches.get('d.tsx')).toEqual({ groupId: 'group-1', extraLines: 1 });
    expect(result.partialMatches.has('e.tsx')).toBe(false);
  });
  test('normalisation', () =>
    expect(normaliseLine("  import {a,b} from '../../x'")).toBe("import {‹names›} from '‹up›/x'"));
  test('needs at least 3 files', () => expect(findSameEdits(['a.tsx', 'b.tsx'], diffs).groups).toHaveLength(0));
});
