const TRANSLATION_EXTENSION = /\.(json|ya?ml|po|pot|strings|stringsdict|xliff|xlf|arb|properties)$/i;
const TRANSLATION_FOLDERS = new Set(['locales', 'locale', 'i18n', 'l10n', 'translations', 'lang', 'langs', 'messages']);
const INDENT_SIGNIFICANT =
  /(\.(py|pyi|ya?ml|mk|sass|styl|pug|jade|haml|slim|coffee|nim|fs|fsx|hs|elm)$)|(^|\/)(GNU)?[Mm]akefile$/;
const GENERATED_HEADER = /@generated|DO NOT EDIT|Code generated by/i;

/** Which buckets are switched on; a bucket missing from the record counts as on. */
export const bucketSettingsSchema = zod.partialRecord(bucketIdSchema, zod.boolean());
export type BucketSettings = zod.infer<typeof bucketSettingsSchema>;

const fileName = (path: string) => path.slice(path.lastIndexOf('/') + 1);
const folderNames = (path: string) => path.split('/').slice(0, -1);

/**
 * Removed and added lines are the same, in the same order, once indentation, trailing
 * whitespace and whitespace runs are normalised. Whitespace *between* tokens is kept
 * (".a .b" vs ".a.b" or "My App" vs "MyApp" are real changes). Blank lines are ignored.
 */
export function isWhitespaceOnly(diff: FileDiff): boolean {
  const normalise = (text: string) => text.replace(/\s+/g, ' ').trim();
  const added: string[] = [];
  const removed: string[] = [];
  for (const line of diff.lines) {
    if (line.kind === 'addition') added.push(normalise(line.text));
    else if (line.kind === 'deletion') removed.push(normalise(line.text));
  }
  if (!added.length && !removed.length) return false;
  const addedText = added.filter(Boolean);
  const removedText = removed.filter(Boolean);
  return addedText.length === removedText.length && addedText.every((text, index) => text === removedText[index]);
}

/** First matching rule wins; anything uncertain stays in Needs review. */
export function classify(file: FileSummary, diff: FileDiff | undefined, settings: BucketSettings = {}): Bucket {
  const enabled = (id: BucketId) => settings[id] !== false;
  const name = fileName(file.path);
  const changed = file.additions + file.deletions;
  if (enabled('renamed') && file.status === 'renamed' && changed === 0)
    return { id: 'renamed', reason: `renamed from ${file.oldPath ?? 'another path'}, no content changes` };
  if (enabled('deleted') && file.status === 'deleted') return { id: 'deleted', reason: 'file deleted' };
  if (enabled('lockfile') && LOCKFILES.has(name)) return { id: 'lockfile', reason: `lockfile: ${name}` };
  if (enabled('generated')) {
    if (file.isGenerated || diff?.isGenerated)
      return { id: 'generated', reason: 'generated: GitHub linguist / .gitattributes' };
    if (file.isVendored) return { id: 'generated', reason: 'vendored: GitHub linguist / .gitattributes' };
    const header = diff?.lines
      .slice(0, 12)
      .find(
        line =>
          (line.kind === 'context' || line.kind === 'addition') &&
          (line.newNumber ?? 99) <= 5 &&
          GENERATED_HEADER.test(line.text),
      );
    if (header) return { id: 'generated', reason: `generated: header "${header.text.trim().slice(0, 60)}"` };
  }
  if (enabled('snapshot') && (name.endsWith('.snap') || folderNames(file.path).includes('__snapshots__')))
    return { id: 'snapshot', reason: 'test snapshot' };
  if (enabled('translations') && TRANSLATION_EXTENSION.test(name)) {
    const folder = folderNames(file.path).find(folderName => TRANSLATION_FOLDERS.has(folderName.toLowerCase()));
    if (folder) return { id: 'translations', reason: `translation file in ${folder}/` };
  }
  if (enabled('whitespace') && diff?.complete && !INDENT_SIGNIFICANT.test(file.path) && isWhitespaceOnly(diff)) {
    return { id: 'whitespace', reason: 'only whitespace changed' };
  }
  return { id: 'review', reason: 'needs review' };
}
