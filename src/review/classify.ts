import * as zod from 'zod';
import type { FileDiff, FileSummary } from '../shared/types.ts';

export const bucketIdSchema = zod.enum([
  'review',
  'renamed',
  'deleted',
  'lockfile',
  'generated',
  'snapshot',
  'translations',
  'whitespace',
  'sameEdit',
]);
export type BucketId = zod.infer<typeof bucketIdSchema>;

export interface Bucket {
  id: BucketId;
  reason: string;
}

export interface BucketInfo {
  id: BucketId;
  label: string;
  lowRisk: boolean;
  color: string;
  pill?: string;
}

